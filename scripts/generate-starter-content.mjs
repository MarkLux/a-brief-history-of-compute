function practiceMetadata(lesson) {
  const conceptNames = CONCEPTS_BY_LESSON[lesson.id] ?? ['核心问题', '关键机制', '设计取舍'];
  const fallbackTasks = [
    ['explain', `请用 150 字以内解释《${lesson.title}》中“${conceptNames[0]}”解决了什么问题。`, ['指出它要解决的具体问题', '说明它和上下文中其他概念的关系', '避免只复述定义']],
    ['compare', `请比较“${conceptNames[0]}”和“${conceptNames[1] ?? conceptNames[0]}”的区别与联系。`, ['分别说明两个概念的作用', '说明二者如何协作或互相影响', '给出一个来自文章语境的例子']],
  ];
  const tasks = (PRACTICE_BY_LESSON[lesson.id] ?? fallbackTasks).map((item, index) => ({
    id: `p${String(index + 1).padStart(2, '0')}`,
    type: item[0],
    prompt: item[1],
    rubric: item[2],
    answer: item[3] ?? item[2].map((point) => `答案应覆盖：${point}`),
  }));
  return { lesson_id: lesson.id, tasks };
}

for (const chapter of manifest.course.chapters) {
  chapter.lessons.forEach((lesson, index) => {
    writeYaml(`content/lessons/${lesson.id}.yaml`, lessonMetadata(chapter, lesson, index));
    writeYaml(`content/quizzes/${lesson.id}.yaml`, quizMetadata(lesson));
    writeYaml(`content/practice/${lesson.id}.yaml`, practiceMetadata(lesson));
  });
}

