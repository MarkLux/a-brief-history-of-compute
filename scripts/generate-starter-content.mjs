function fallbackQuizMetadata(lesson) {
  const conceptNames = CONCEPTS_BY_LESSON[lesson.id] ?? ['核心问题', '关键机制', '设计取舍'];
  const conceptIds = conceptNames.map(slugifyConcept);
  return conceptNames.slice(0, 3).map((name, index) => ({
    concept: index,
    question: `《${lesson.title}》中“${name}”主要解决什么问题？`,
    options: [`理解 ${name} 的问题背景和机制`, '只记住名词翻译', '跳过上下文直接背结论', '只关注图片编号'],
    answer: 0,
    explanation: `这道题检查你是否理解 ${name} 的问题背景、工作机制和设计取舍，而不是只记住名词。`,
    source_anchor: conceptIds[index] ?? conceptIds[0],
  }));
}

function quizMetadata(lesson) {
  const conceptIds = (CONCEPTS_BY_LESSON[lesson.id] ?? ['核心问题', '关键机制', '设计取舍']).map(slugifyConcept);
  const quizItems = [
    ...(QUIZZES_BY_LESSON[lesson.id] ?? fallbackQuizMetadata(lesson)),
    ...(EXTRA_QUIZZES_BY_LESSON[lesson.id] ?? []),
  ];
  const questions = quizItems.map((item, index) => ({
    id: `q${String(index + 1).padStart(2, '0')}`,
    type: 'single-choice',
    question: item[0] ?? item.question,
    options: item[1] ?? item.options,
    answer: item[2] ?? item.answer,
    explanation: item[3] ?? item.explanation,
    source_anchor: conceptIds[item[4] ?? item.concept ?? 0] ?? conceptIds[0],
  }));
  return { lesson_id: lesson.id, questions };
}


